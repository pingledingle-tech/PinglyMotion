#!/usr/bin/env python3
"""Makes src/scriptlab/lslbuiltins_extra.inc: the LSL names the viewer keyword list lacks.

    gen_lsl_extra.py LSL_DEFINITIONS_YAML [BASE_INC [OUTPUT]]

LSL_DEFINITIONS_YAML is `lsl_definitions.yaml` from
https://github.com/secondlife/lsl-definitions (Linden Research, Inc., MIT licence),
the source Second Life itself keeps its function, event and constant lists in. It is
newer than the viewer's keyword list that tools/gen_lsl_builtins.py reads. It is not
stored in this repository.

BASE_INC (default src/scriptlab/lslbuiltins_data.inc) is the file made from the
viewer's list. Every function, event and constant that the definitions have and the
base file lacks goes into the output, in the same macro format. Functions marked
god-mode are left out (the other entries marked private or deprecated are kept: scripts
that use them still compile in Second Life, so the checker must know them). Tooltips are left out.

Needs PyYAML (this tool only; nothing in the build uses it). Output is sorted, so a
rerun with the same inputs gives the same bytes.
"""
import os
import re
import sys

import yaml

TYPES = {"integer", "float", "string", "key", "vector", "rotation", "list", "void"}


def c_string(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            raise SystemExit("unexpected character %r in %r" % (ch, text))
    return '"' + "".join(out) + '"'


def arguments(func):
    types, names = [], []
    for entry in func.get("arguments") or []:
        (name, info), = entry.items()
        if info["type"] not in TYPES:
            raise SystemExit("unknown type %r" % info["type"])
        types.append(info["type"])
        names.append(name)
    return ",".join(types), ",".join(names)


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    here = os.path.dirname(os.path.abspath(__file__))
    base_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "..", "src", "scriptlab", "lslbuiltins_data.inc")
    out_path = sys.argv[3] if len(sys.argv) > 3 else os.path.join(here, "..", "src", "scriptlab", "lslbuiltins_extra.inc")
    with open(sys.argv[1], encoding="utf-8") as f:
        defs = yaml.safe_load(f)
    with open(base_path, encoding="utf-8") as f:
        base = f.read()
    have_f = set(re.findall(r'LSL_FUNCTION\("(\w+)"', base))
    have_e = set(re.findall(r'LSL_EVENT\("(\w+)"', base))
    have_c = set(re.findall(r'LSL_CONSTANT\("(\w+)"', base))

    lines = []
    for name in sorted(defs["functions"]):
        func = defs["functions"][name]
        if name in have_f or func.get("god-mode"):
            continue
        types, names = arguments(func)
        ret = func["return"]
        if ret not in TYPES:
            raise SystemExit("unknown return type %r" % ret)
        lines.append("LSL_FUNCTION(%s, %s, %s, %s, %d)" % (
            c_string(name), c_string(ret), c_string(types), c_string(names), 1 if func.get("deprecated") else 0))
    for name in sorted(defs["events"]):
        event = defs["events"][name]
        if name in have_e:
            continue
        types, _ = arguments(event)
        lines.append("LSL_EVENT(%s, %s)" % (c_string(name), c_string(types)))
    for name in sorted(defs["constants"]):
        const = defs["constants"][name]
        if name in have_c:
            continue
        if const["type"] not in TYPES:
            raise SystemExit("unknown type %r" % const["type"])
        lines.append("LSL_CONSTANT(%s, %s, %s)" % (c_string(name), c_string(const["type"]), c_string(str(const["value"]))))

    header = """// Generated by tools/gen_lsl_extra.py from lsl_definitions.yaml of
// https://github.com/secondlife/lsl-definitions (Linden Research, Inc., MIT licence):
// the functions, events and constants that the viewer's keyword list (lslbuiltins_data.inc)
// lacks. Names, signatures and constant values only. Do not edit by hand.
//
// LSL_FUNCTION(name, return type, argument types, argument names, deprecated)
// LSL_EVENT(name, argument types)
// LSL_CONSTANT(name, type, value)

"""
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(header + "\n".join(lines) + "\n")
    print("%d entries" % len(lines))


if __name__ == "__main__":
    main()
