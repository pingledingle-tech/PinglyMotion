#!/usr/bin/env python3
"""Makes src/scriptlab/lslbuiltins_data.inc from the viewer's LSL keyword list.

    gen_lsl_builtins.py KEYWORDS_XML [OUTPUT]

KEYWORDS_XML is `indra/newview/app_settings/keywords_lsl_default.xml` from the
Second Life viewer or the Firestorm viewer (same file and format; LGPL 2.1,
Linden Research, Inc. and the Firestorm project). It is not stored in this
repository; download it first, for example from
https://github.com/secondlife/viewer (branch "release").

The output lists every LSL function (name, return type, argument types and
names), every event (name, argument types) and every constant (name, type,
value), as C macro calls that src/scriptlab/lsl/builtins.cpp expands. Tooltips
are left out. The interpreter uses the list to check calls and to say "not
supported yet" for functions it knows but does not run.

Standard library only. Output is sorted, so a rerun with the same input gives
the same bytes.
"""
import sys
import xml.etree.ElementTree as ET

TYPES = {"integer", "float", "string", "key", "vector", "rotation", "list", "void", ""}


def llsd(node):
    """LLSD XML element to Python value."""
    tag = node.tag
    if tag == "map":
        out = {}
        children = list(node)
        for i in range(0, len(children) - 1, 2):
            out[children[i].text or ""] = llsd(children[i + 1])
        return out
    if tag == "array":
        return [llsd(child) for child in node]
    if tag == "integer":
        return int(node.text or "0")
    if tag == "real":
        return float(node.text or "0")
    if tag == "boolean":
        return (node.text or "").strip() in ("1", "true")
    return node.text or ""


def c_string(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            raise SystemExit("unexpected character %r in %r" % (ch, text))
    return '"' + "".join(out) + '"'


def arguments(entry):
    types, names = [], []
    for arg in entry.get("arguments", []) or []:
        for name, info in arg.items():
            kind = info.get("type", "")
            if kind not in TYPES:
                raise SystemExit("unknown type %r" % kind)
            types.append(kind)
            names.append(name)
    return ",".join(types), ",".join(names)


def constant_value(kind, raw):
    text = str(raw)
    if kind == "string":
        # the file writes "\n" in strings as a backslash pair; LSL source would read it as an escape
        text = text.replace("\\\\n", "\n").replace("\\n", "\n").replace('\\"', '"')
        if text.startswith('"') and text.endswith('"') and len(text) >= 2:
            text = text[1:-1]
    return text


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    root = ET.parse(sys.argv[1]).getroot()
    data = llsd(root[0])
    lines = [
        "// Generated by tools/gen_lsl_builtins.py from the viewer's keywords_lsl_default.xml",
        "// (Second Life viewer / Firestorm viewer, LGPL 2.1, Linden Research, Inc. and the",
        "// Firestorm project). Names, signatures and constant values only. Do not edit by hand.",
        "//",
        "// LSL_FUNCTION(name, return type, argument types, argument names, deprecated)",
        "// LSL_EVENT(name, argument types)",
        "// LSL_CONSTANT(name, type, value)",
        "",
    ]
    for name in sorted(data.get("functions", {})):
        entry = data["functions"][name]
        if entry.get("god-mode"):
            continue
        ret = entry.get("return", "void") or "void"
        if ret not in TYPES:
            raise SystemExit("unknown return type %r" % ret)
        types, names = arguments(entry)
        lines.append("LSL_FUNCTION(%s, %s, %s, %s, %d)" % (c_string(name), c_string(ret), c_string(types),
                                                         c_string(names), 1 if entry.get("deprecated") else 0))
    lines.append("")
    for name in sorted(data.get("events", {})):
        types, _ = arguments(data["events"][name])
        lines.append("LSL_EVENT(%s, %s)" % (c_string(name), c_string(types)))
    lines.append("")
    for name in sorted(data.get("constants", {})):
        entry = data["constants"][name]
        kind = entry.get("type", "")
        if "value" not in entry:
            continue  # "default" is listed with the constants but is the state keyword
        if kind not in TYPES or kind in ("", "void"):
            raise SystemExit("unknown constant type %r for %s" % (kind, name))
        value = constant_value(kind, entry.get("value", ""))
        lines.append("LSL_CONSTANT(%s, %s, %s)" % (c_string(name), c_string(kind), c_string(value)))
    text = "\n".join(lines) + "\n"
    if len(sys.argv) > 2:
        with open(sys.argv[2], "w", encoding="ascii", newline="\n") as handle:
            handle.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
