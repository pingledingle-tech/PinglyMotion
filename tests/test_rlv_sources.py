#!/usr/bin/env python3
"""Tests for tools/rlv_sources.py (the RLV source data files, tests/data/rlv/)."""
import os
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "tools"))
import rlv_sources as r  # noqa: E402

DATA = os.path.join(HERE, "data", "rlv")

# A made-up dictionary in the shape of RLVa's (own test lines, not copied from RLVa).
FAKE_RLVA = """
RlvBehaviourDictionary::RlvBehaviourDictionary()
{
    memset(m_Mods, 0, 4);
    addEntry(new RlvBehaviourGenericProcessor<RLV_OPTION_NONE>("alpha", RLV_BHVR_A));
    addEntry(new RlvBehaviourGenericProcessor<RLV_OPTION_NONE_OR_EXCEPTION>("beta", RLV_BHVR_B, RlvBehaviourInfo::BHVR_STRICT | RlvBehaviourInfo::BHVR_EXTENDED));
    addModifier(RLV_BHVR_B, RLV_MODIFIER_B, new RlvBehaviourModifier("B", 0.0f, true, nullptr));
    addEntry(new RlvBehaviourInfo("gamma",   RLV_BHVR_G,  RLV_TYPE_REPLY));
    addEntry(new RlvForceProcessor<RLV_BHVR_A>("alpha"));
    addEntry(new RlvBehaviourInfo("delta",   RLV_CMD_FORCEWEAR,  RLV_TYPE_FORCE, RlvBehaviourInfo::FORCEWEAR_NODE
                                                                 | RlvBehaviourInfo::BHVR_SYNONYM));
    // a comment ("omega", RLV_TYPE_FORCE)
    RlvBehaviourInfo* pEps = new RlvBehaviourProcessor<RLV_BHVR_E>("eps");
    pEps->addModifier(ERlvLocalBhvrModifier::X, typeid(float), "size", &f);
    addEntry(pEps);
    addEntry(new RlvReplyProcessor<RLV_BHVR_Z>("zeta", RlvBehaviourInfo::BHVR_EXPERIMENTAL));

    // Populate m_String2InfoMap
}
"""


class RlvaReader(unittest.TestCase):
    def test_fake_dictionary(self):
        t = r.read_rlva(FAKE_RLVA)
        self.assertEqual(t.lines(), [
            "alpha\trestriction,force\t",
            "beta\trestriction\textended",
            "beta_sec\trestriction\textended,secure-form",
            "delta\tforce\tsynonym",
            "eps\trestriction\t",
            "eps_size\tforce\tmodifier",
            "gamma\tquery\t",
            "zeta\tquery\texperimental",
        ])

    def test_unknown_line_fails(self):
        text = FAKE_RLVA.replace("// a comment", "addEntry(new SomethingNew(\"x\"));\n    //")
        with self.assertRaises(r.SourceError):
            r.read_rlva(text)

    def test_unknown_flag_fails(self):
        with self.assertRaises(r.SourceError):
            r.read_rlva(FAKE_RLVA.replace("BHVR_EXTENDED", "BHVR_NEWFLAG"))

    def test_missing_constructor_fails(self):
        with self.assertRaises(r.SourceError):
            r.read_rlva("int main() {}")


class WikiReader(unittest.TestCase):
    def test_forms(self):
        text = ("Allow/prevent flying : @fly=<y/n>\n@recvchat:<UUID>=<rem/add>\n@sit:<UUID>=force\n"
                "@getstatus[:<part>[;<sep>]]=<channel>\n@version=<channel_number>\n@clear=<string>\n"
                "@setenv_<setting>:<value>=force (*)\nsee @getblacklist\n"
                "== Unofficial Commands ==\n@allowidle=<y/n>\n")
        self.assertEqual(r.read_wiki(text).lines(), [
            "allowidle\trestriction\tunofficial",
            "fly\trestriction\t",
            "getstatus\tquery\t",
            "recvchat\trestriction\t",
            "setenv_*\tforce\t",
            "sit\tforce\t",
            "version\tquery\t",
        ])

    def test_committed_wiki_file_is_generated_from_the_capture(self):
        with open(os.path.join(DATA, "rlv_wiki_capture.txt"), encoding="utf-8") as f:
            table = r.read_wiki(f.read())
        with open(os.path.join(DATA, "rlv_wiki.tsv"), encoding="utf-8") as f:
            committed = [line.rstrip("\n") for line in f if not line.startswith("#")]
        self.assertEqual(committed, table.lines())

    def test_committed_files_have_the_header(self):
        for name in ("rlva.tsv", "rlv_wiki.tsv"):
            with open(os.path.join(DATA, name), encoding="utf-8") as f:
                self.assertTrue(f.readline().startswith("# Generated by tools/rlv_sources.py"), name)


class CommandLine(unittest.TestCase):
    def test_writes_the_file(self):
        with tempfile.TemporaryDirectory() as d:
            src = os.path.join(d, "helper.cpp")
            out = os.path.join(d, "out.tsv")
            with open(src, "w", encoding="utf-8") as f:
                f.write(FAKE_RLVA)
            self.assertEqual(r.main(["rlva", src, "--out", out, "--source", "a test"]), 0)
            with open(out, encoding="utf-8") as f:
                lines = f.read().splitlines()
            self.assertEqual(lines[0], "# Generated by tools/rlv_sources.py rlva; do not edit by hand.")
            self.assertEqual(lines[1], "# Source: a test")
            self.assertIn("eps_size\tforce\tmodifier", lines)

    def test_bad_source_exit_code(self):
        with tempfile.TemporaryDirectory() as d:
            src = os.path.join(d, "helper.cpp")
            with open(src, "w", encoding="utf-8") as f:
                f.write("nothing here")
            self.assertEqual(r.main(["rlva", src, "--out", os.path.join(d, "o.tsv")]), 1)


if __name__ == "__main__":
    unittest.main()
